// MongoDB $jsonSchema validators. These are installed with validationLevel
// "strict" and validationAction "error" by migration 001. App-level validation
// is additional and never a replacement for these definitions.

const DECIMAL = "decimal";
const DATE = "date";
const STRING = "string";
const BOOL = "bool";
const OBJECT = "object";
const OID = "objectId";
const ARRAY = "array";
const NUMBER = "number";

function prop(bsonType, extra = {}) {
  return { bsonType, ...extra };
}

const LEGACY = {
  legacy_unverified: prop(BOOL),
  provenance: prop(STRING, { enum: ["sqlite-import", "app", "evaluator", "seed", "migration"] }),
  legacy_ref: prop(STRING),
};

const MONEY = prop(DECIMAL);
const PRICE = prop(DECIMAL);
const TS = prop(DATE);
const ID = prop(OID);

function schema(title, required, properties, { additionalProperties = false } = {}) {
  return {
    $jsonSchema: {
      bsonType: OBJECT,
      title,
      required,
      // _id is generated by the driver before validation and must be declared
      // when additionalProperties is false.
      properties: { _id: ID, ...properties },
      additionalProperties,
    },
  };
}

